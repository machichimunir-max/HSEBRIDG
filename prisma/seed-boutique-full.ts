async function main() {
  console.log('🌱 Seeding Boutique categories with images and realistic products...\n');

  // 1. Upsert categories with images
  for (const category of categoriesWithImages) {
    await prisma.productCategory.upsert({
      where: { slug: category.slug },
      update: {
        ...category,
        image: category.image, // Add image field
      },
      create: category,
    });
    console.log(`✅ Category: ${category.titleFr} (with image)`);
  }

  console.log('\n📦 Seeding realistic products with specifications and images...\n');

  // 2. Create products
  for (const product of products) {
    const category = await prisma.productCategory.findUnique({
      where: { slug: product.categorySlug },
    });

    if (!category) {
      console.log(`⚠️  Category not found: ${product.categorySlug}, skipping product ${product.titleFr}`);
      continue;
    }

    await prisma.product.upsert({
      where: { slug: product.slug },
      update: {
        titleFr: product.titleFr,
        titleAr: product.titleAr,
        sku: product.sku,
        shortDescFr: product.shortDescFr,
        shortDescAr: product.shortDescAr,
        descriptionFr: product.descriptionFr,
        descriptionAr: product.descriptionAr,
        images: product.images,
        price: product.price,
        stockStatus: product.stockStatus,
        certifications: product.certifications,
        specifications: product.specifications,
        isFeatured: product.isFeatured,
        isVisible: product.isVisible,
        order: product.order,
        categoryId: category.id,
      },
      create: {
        ...product,
        categoryId: category.id,
        // Remove categorySlug from create data
        categorySlug: undefined,
      } as any,
    });

    console.log(`✅ Product: ${product.titleFr} (${product.sku})`);
  }

  console.log('\n✨ Seed completed! Summary:');
  console.log(`   📁 ${categoriesWithImages.length} categories with professional images`);
  console.log(`   📦 ${products.length} realistic products with full specifications`);
  console.log('   🏆 Products include certifications (EN, ISO, ANSI, CE)');
  console.log('   🖼️  High-quality product images from Unsplash');
  console.log('   💰 Realistic pricing in MAD');
  console.log('\n🚀 Ready to showcase a professional HSE equipment store!');
}

main()
  .catch((e) => {
    console.error('❌ Seeding error:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
